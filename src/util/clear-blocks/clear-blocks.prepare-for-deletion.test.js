import "babel-polyfill";
import {
    prepareForDeletion,
    commitColumnAsSweeping,
    revertUncommittedMarks,
} from './index.js';


describe('prepareForDeletion', () => {
    it('marks only valid 2x2 same-color squares resting on the bottom', async () => {
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', 'B', 'B', '|', '|', '|'],

            ['|', '|', '|', '|', '|', 'B', 'B', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'B', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'],

        ];
        await prepareForDeletion(array);

        expect(array).toStrictEqual([
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', 'B', 'B', '|', '|', '|'],

            ['|', '|', '|', '|', '|', 'B', 'B', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'B', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'a', 'a'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'a', 'a'],
        ]);
    });

    it('special block does not trigger when 2x2 is mixed color', async () => {
        // col 9 r9 = B breaks the 2x2 — no valid square, nothing gets marked
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '@', 'A'], // col 8: special A (@), regular A
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'B'], // col 9: r8=A, r9=B ← breaks the 2x2
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 10
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];
        await prepareForDeletion(array);
        expect(array[8][8]).toBe('@'); // special A — unchanged
        expect(array[8][9]).toBe('A');
        expect(array[9][8]).toBe('A');
        expect(array[9][9]).toBe('B'); // B — unchanged
        expect(array[10][8]).toBe('A');
        expect(array[10][9]).toBe('A');
    });

    it('special block flood fill stops at adjacent different-color block', async () => {
        // col 10 r9 = B — valid 2x2 at cols 8-9, flood fill reaches col 10 r8 (A) but not r9 (B)
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '@', 'A'], // col 8: special A (@), regular A
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 9: A pair completing 2x2
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'B'], // col 10: r8=A (in flood fill), r9=B ← stops here
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];
        await prepareForDeletion(array);
        expect(array[8][8]).toBe('*');  // special A → deletion-special-A
        expect(array[8][9]).toBe('a');
        expect(array[9][8]).toBe('a');
        expect(array[9][9]).toBe('a');
        expect(array[10][8]).toBe('a'); // flood fill reached the A
        expect(array[10][9]).toBe('B'); // B survives — flood fill stopped here
    });

    it('special block triggers chain deletion of adjacent same-color blocks', async () => {
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '@', 'A'], // col 8: special A (@), regular A
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 9: regular A pair completing 2x2
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 10: adjacent same-color neighbor
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];
        await prepareForDeletion(array);
        expect(array[8][8]).toBe('*');
        expect(array[8][9]).toBe('a');
        expect(array[9][8]).toBe('a');
        expect(array[9][9]).toBe('a');
        expect(array[10][8]).toBe('a');
        expect(array[10][9]).toBe('a');
    });

    it('group formed mid-swiper: cols behind swiper revert, cols ahead are swept', async () => {
        // Swiper is at col 9 when the 2x2 forms at cols 8-9 (flood fill reaches col 10).
        // Col 8 was already passed — its marks revert when swiper exits.
        // Cols 9 and 10 are at/ahead of swiper — they get committed as SWEEP.
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '@', 'A'], // col 8: special A (@), regular A
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 9: regular A pair completing 2x2
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 10: adjacent same-color neighbor
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];
        await prepareForDeletion(array);
        await commitColumnAsSweeping(array, 9);
        await commitColumnAsSweeping(array, 10);
        await revertUncommittedMarks(array);

        // col 8 was behind the swiper — reverts to original blocks
        expect(array[8][8]).toBe('@'); // back to special A
        expect(array[8][9]).toBe('A'); // back to regular A

        // cols 9 and 10 were swept — SWEEP_TYPE_A
        expect(array[9][8]).toBe('S');
        expect(array[9][9]).toBe('S');
        expect(array[10][8]).toBe('S');
        expect(array[10][9]).toBe('S');
    });

    it('mixed 1+3 square is detected as color A deletion', async () => {
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '@', 'A'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', '@'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];
        await prepareForDeletion(array);
        // Special blocks (@) become *; normal blocks (A) become a
        expect(array[8][8]).toBe('*');
        expect(array[9][8]).toBe('a');
        expect(array[8][9]).toBe('a');
        expect(array[9][9]).toBe('*');
    });

    it('special block chains across multiple columns and marks all via flood fill', async () => {
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'], // col 0
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'], // col 1
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'], // col 2
            ['|', '|', '|', '|', '|', '|', '|', '|', '@', 'A'], // col 3: special A + regular A (anchors 2x2)
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'], // col 4: regulars completing 2x2
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', '|'], // col 5: chain
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', '|'], // col 6: chain
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', '|'], // col 7: chain end
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'], // col 8
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];

        await prepareForDeletion(array);

        // All chain cells get marked (special as *, regulars as a)
        expect(array[3][8]).toBe('*');
        expect(array[3][9]).toBe('a');
        expect(array[4][8]).toBe('a');
        expect(array[4][9]).toBe('a');
        expect(array[5][8]).toBe('a');
        expect(array[6][8]).toBe('a');
        expect(array[7][8]).toBe('a');
    });
});
