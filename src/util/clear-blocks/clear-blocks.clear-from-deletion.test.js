import "babel-polyfill";
import {
    clearFromDeletion,
} from './index.js';


describe('clearFromDeletion', () => {
    it('reverts deletion markers back to live block types', async () => {
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],

            ['|', '|', '|', '|', '|', 'B', 'B', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'B', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'a', 'a'],

        ];
        await clearFromDeletion(array);
        expect(array).toStrictEqual([
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['A', 'A', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],

            ['|', '|', '|', '|', '|', 'B', 'B', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'B', 'B'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'A', 'A'],
        ]);
    });

    it('reverts special deletion marks to their special block types', async () => {
        let array = [
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '*', '~'],
            ['|', '|', '|', '|', '|', '|', '|', '|', 'a', 'b'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
            ['|', '|', '|', '|', '|', '|', '|', '|', '|', '|'],
        ];
        await clearFromDeletion(array);
        expect(array[8][8]).toBe('@'); // * → special A
        expect(array[8][9]).toBe('%'); // ~ → special B
        expect(array[9][8]).toBe('A'); // a → normal A
        expect(array[9][9]).toBe('B'); // b → normal B
    });
});
